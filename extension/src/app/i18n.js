export const LANGS = ['de', 'en'];

let lang = 'de';

export const getLang = () => lang;
export const locale = () => (lang === 'de' ? 'de-AT' : 'en-GB');

export function setLang(next) {
  lang = LANGS.includes(next) ? next : 'de';
  document.documentElement.lang = lang;
}

export function t(key, vars = {}) {
  const template = STRINGS[lang][key] ?? STRINGS.de[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

export function feature(code) {
  const entry = FEATURES[code];
  if (entry === null) return null;
  if (entry) return entry[lang === 'de' ? 0 : 1];
  if (/^[A-Z_]+$/.test(code)) return code.toLowerCase().replace(/_/g, ' ').replace(/^\w/, (c) => c.toUpperCase());
  return code;
}

export function applyStatic(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
}
